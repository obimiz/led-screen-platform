import { Schema, model, models } from "mongoose";
import { assessmentStatuses } from "@/lib/installations/constants";
const t = { type: String, default: "", trim: true };
const schema = new Schema(
  {
    assessmentNumber: { type: String, unique: true, required: true },
    installationRequestId: {
      type: Schema.Types.ObjectId,
      ref: "InstallationRequest",
      required: true,
      unique: true,
    },
    scheduledDate: t,
    scheduledTime: t,
    assignedStaff: [{ type: Schema.Types.ObjectId, ref: "Admin" }],
    venueName: t,
    address: t,
    locationNotes: t,
    buildingType: t,
    mountingSurface: t,
    structuralCondition: t,
    availableWidth: Number,
    availableHeight: Number,
    mountingHeight: Number,
    powerSupply: t,
    powerRequirement: t,
    cableRoute: t,
    controlRoomLocation: t,
    ventilation: t,
    weatherExposure: t,
    internetConnectivity: t,
    accessRestrictions: t,
    safetyNotes: t,
    technicianNotes: t,
    recommendedProductId: {
      type: Schema.Types.ObjectId,
      ref: "Product",
      default: null,
    },
    recommendedProductSnapshot: Schema.Types.Mixed,
    recommendedWidth: Number,
    recommendedHeight: Number,
    recommendedPixelPitch: t,
    recommendedMountingMethod: t,
    recommendedAccessories: [Schema.Types.Mixed],
    estimatedInstallationDuration: t,
    siteImageUrls: [String],
    status: { type: String, enum: assessmentStatuses, default: "scheduled" },
    assessedBy: { type: Schema.Types.ObjectId, ref: "Admin", default: null },
    completedAt: Date,
  },
  { timestamps: true, optimisticConcurrency: true },
);
export const SiteAssessment =
  models.SiteAssessment || model("SiteAssessment", schema);
